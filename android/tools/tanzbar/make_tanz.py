"""The Tanzbär Lite's instrument profile: measured.tsv (tune tables and decay curves from the sweep recording) and
styles.tsv (each style's sound) -> app/src/main/java/com/grum0/gen1/TanzData.kt. Run after editing either; commit
the output. `--check` exits 1 if TanzData.kt is stale. Styles are matched to app/gen.h's style enum by name."""
import math, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..', '..')
OUT = os.path.join(HERE, '..', '..', 'app', 'src', 'main', 'java', 'com', 'grum0', 'gen1', 'TanzData.kt')
PCS = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}
# styles.tsv's columns: (CC, a length in ms?)
COLS = [('kick', 64, 1), ('ktone', 2, 0), ('stone', 11, 0), ('snoise', 13, 0), ('snare', 67, 1), ('cfilt', 18, 0),
        ('clap', 75, 1), ('catk', 76, 0), ('tom', 20, 1), ('conga', 78, 1), ('bell', 85, 1), ('clave', 87, 1),
        ('cytone', 92, 0), ('cymbal', 88, 1), ('chat', 91, 1), ('ohat', 90, 1)]
TUNES = [('KICK', 3), ('TOM', 19), ('CONGA', 79), ('BELL', 84), ('CLAVE', 86)]
BELL_MELODIC_MS = 45                                 # the cowbell's length when it plays a line (sweep doc: CC about 40)


def rows(name):
    for n, line in enumerate(open(os.path.join(HERE, name), encoding='utf-8'), 1):
        line = line.rstrip('\n')                     # (comments are whole lines: note names have #)
        if line.strip() and not line.startswith('#'):
            yield n, line.split('\t')


def enum_styles():
    h = open(os.path.join(ROOT, 'app', 'gen.h'), encoding='utf-8').read()
    body = h[h.index('enum { GS_'):]
    body = body[:body.index('GEN_NSTYLES')]
    return re.findall(r'GS_[A-Z0-9_]+', body)


def main():
    tune, decay = {}, {}
    for n, r in rows('measured.tsv'):
        if r[0] == 'tune':
            pc = PCS[re.match(r'[A-G]#?', r[2]).group(0)]
            tune.setdefault(int(r[1]), [-1] * 12)[pc] = int(r[3])
        elif r[0] == 'decay':
            decay[int(r[1])] = [float(x) for x in r[2:7]]
        else:
            sys.exit('measured.tsv:%d: tune or decay' % n)

    def cc_for_ms(cc, ms):                           # log-linear between the five measured points
        pts = list(zip((0, 32, 64, 96, 127), decay[cc]))
        if ms <= pts[0][1]:
            return 0
        for (c0, m0), (c1, m1) in zip(pts, pts[1:]):
            if ms <= m1:
                return round(c0 + (c1 - c0) * (math.log(ms) - math.log(m0)) / (math.log(m1) - math.log(m0)))
        return 127

    names = enum_styles()
    got = {}
    for n, r in rows('styles.tsv'):
        if len(r) != len(COLS) + 2 or r[0] not in names or r[0] in got:
            sys.exit('styles.tsv:%d: a known style, once, with %d values and a tune flag' % (n, len(COLS)))
        vals = [cc_for_ms(cc, float(v)) if ms else int(v) for (_, cc, ms), v in zip(COLS, r[1:-1])]
        if any(v < 0 or v > 127 for v in vals) or any(ch not in 'tcl-' for ch in r[-1]):
            sys.exit('styles.tsv:%d: values 0..127, tune flags t c l or -' % n)
        got[r[0]] = (vals, sum(1 << 'tcl'.index(ch) for ch in r[-1] if ch != '-'))
    missing = [s for s in names if s not in got]
    if missing:
        sys.exit('styles.tsv: no sound for %s' % ' '.join(missing))

    out = ['// SPDX-License-Identifier: GPL-3.0-only',
           '// Generated by android/tools/tanzbar/make_tanz.py from measured.tsv and styles.tsv: do not edit.',
           'package com.grum0.gen1', '',
           '/** The Tanzbär Lite\'s profile: each style\'s sound, and the tune tables measured from its sweep. */',
           'object TanzData {',
           '    /** The controllers a style sets, in the order of each row of STYLE. */',
           '    val CCS = intArrayOf(%s)' % ', '.join(str(cc) for _, cc, _ in COLS),
           '    /** Per style, in the style enum\'s order. */',
           '    val STYLE = arrayOf(']
    for s in names:
        out.append('        intArrayOf(%s), // %s' % (', '.join(map(str, got[s][0])), s[3:]))
    out += ['    )',
            '    /** Per style, the voices besides the kick that follow the key: bit 0 tom, 1 conga, 2 clave. */',
            '    val FOLLOW = intArrayOf(%s)' % ', '.join(str(got[s][1]) for s in names),
            '    /** Tune: the CC, then its value for each pitch class from C; -1 where the drum cannot play it. */']
    for name, cc in TUNES:
        out.append('    const val %s_CC = %d' % (name, cc))
        out.append('    val %s = intArrayOf(%s)' % (name, ', '.join(map(str, tune[cc]))))
    out += ['    /** The cowbell\'s decay while it plays a line (%d ms). */' % BELL_MELODIC_MS,
            '    const val BELL_MELODIC_DECAY = %d' % cc_for_ms(85, BELL_MELODIC_MS),
            '}', '']
    text = '\n'.join(out)
    if '--check' in sys.argv:
        if not os.path.exists(OUT) or open(OUT, encoding='utf-8').read() != text:
            sys.exit('TanzData.kt is out of date: run python3 android/tools/tanzbar/make_tanz.py')
        print('Tanzbar profile: TanzData.kt up to date')
    else:
        open(OUT, 'w', encoding='utf-8').write(text)
        print('Tanzbar profile: %d styles written' % len(names))


main()
