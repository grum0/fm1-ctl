"""Turns the style grids (app/styles/*.grid) into app/style_grids.h: one GRID_<NAME> initializer per style for the
`lane` member of style_t in gen.c. Run after editing a grid; commit both. `--check` exits 1 if the header is stale.

A lane string is 16 weights, as gen.c reads them (wdec): '0' rest, '1'..'9' a hit of that weight, 'a'..'e' a ghost
of weight 5..9. From the grids: X -> 9 (accent), x -> 7 (hit), r -> 8 (a hit the style's ratchets may double),
o -> b (ghost), . -> 0."""
import glob, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'style_grids.h')
LANES = {'kick': 'L_KICK', 'snare': 'L_SNARE', 'rim': 'L_RIM', 'clap': 'L_CLAP', 'chat': 'L_CHH', 'ohat': 'L_OHH',
         'tom': 'L_TOML', 'conga': 'L_CONGH', 'cowbell': 'L_COWB', 'claves': 'L_CLAVE', 'cymbal': 'L_CYM',
         'zap': 'L_SIM1', 'noise': 'L_SIM2'}
CODE = {'X': '9', 'x': '7', 'r': '8', 'o': 'b', '.': '0'}


def parse(path):
    styles, cur = [], None
    for n, line in enumerate(open(path, encoding='utf-8'), 1):
        line = line.split('#', 1)[0].rstrip()
        if not line.strip():
            continue
        words = line.split()
        if words[0] == 'style':
            cur = (words[1], [])
            styles.append(cur)
            continue
        if cur is None or words[0] not in LANES:
            sys.exit('%s:%d: expected "style NAME" or a lane (%s)' % (path, n, ' '.join(LANES)))
        steps = ''.join(words[1:])
        if len(steps) != 16 or any(c not in CODE for c in steps):
            sys.exit('%s:%d: a lane is 16 steps of X x r o .' % (path, n))
        if any(l == words[0] for l, _ in cur[1]):
            sys.exit('%s:%d: lane %s twice' % (path, n, words[0]))
        cur[1].append((words[0], ''.join(CODE[c] for c in steps)))
    return styles


def render():
    out = ['/* SPDX-License-Identifier: GPL-3.0-or-later */',
           '/* Generated by app/styles/make_grids.py from the .grid files in app/styles: do not edit. One bar of 16 weights a lane',
           ' * (as wdec reads them), the `lane` member of a style in gen.c. */',
           '#pragma once', '']
    seen = set()
    for path in sorted(glob.glob(os.path.join(HERE, '*.grid'))):
        out.append('/* %s */' % os.path.basename(path))
        for name, lanes in parse(path):
            if name in seen:
                sys.exit('style %s twice' % name)
            seen.add(name)
            body = ', '.join('[%s] = "%s"' % (LANES[l], s) for l, s in lanes)
            out.append('#define GRID_%s {%s}' % (name, body))
        out.append('')
    return '\n'.join(out)


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if old != text:
            sys.exit('app/style_grids.h is out of date: run python3 app/styles/make_grids.py')
        print('style grids: header up to date')
    else:
        open(OUT, 'w', encoding='utf-8').write(text)
        print('style grids: wrote %s' % os.path.relpath(OUT))
